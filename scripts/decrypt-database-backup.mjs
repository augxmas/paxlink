import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import zlib from 'node:zlib';
const [directory, keyFile, output] = process.argv.slice(2);
if (!directory || !keyFile || !output) throw new Error('Usage: node scripts/decrypt-database-backup.mjs BACKUP_DIRECTORY PRIVATE_KEY_FILE OUTPUT.sql');
const manifest = JSON.parse(fs.readFileSync(path.join(directory, 'manifest.json'), 'utf8'));
const recovery = JSON.parse(fs.readFileSync(keyFile, 'utf8'));
const data = fs.readFileSync(path.join(directory, 'data.sql.gz.enc'));
const hash = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
if (data.subarray(0, 8).toString() !== 'PAXSQL1\n' || hash(data) !== manifest.encryptedSha256) throw new Error('Backup file is damaged or does not match the manifest.');
const key = Buffer.from(recovery.backupKeyBase64, 'base64');
if (key.length !== 32) throw new Error('Invalid recovery key.');
const decipher = crypto.createDecipheriv('aes-256-gcm', key, data.subarray(8, 20));
decipher.setAuthTag(data.subarray(20, 36));
const sql = zlib.gunzipSync(Buffer.concat([decipher.update(data.subarray(36)), decipher.final()]));
if (hash(sql) !== manifest.sqlSha256) throw new Error('SQL integrity verification failed.');
fs.mkdirSync(path.dirname(path.resolve(output)), { recursive: true, mode: 0o700 });
fs.writeFileSync(output, sql, { flag: 'wx', mode: 0o600 });
console.log(`Verified SQL written to ${output}. Set PERSONAL_DATA_ENCRYPTION_KEY from the private recovery key before starting the app.`);
